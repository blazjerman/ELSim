import { analyzeConnectivity, pinNet } from '../domain/connectivity'
import type { Part, PartKind, Project } from '../domain/project'

function cleanComment(value: string): string {
  return value.replace(/[\r\n\u0000-\u001f]/g, ' ').trim()
}

function spiceNumber(value: string, kind: PartKind): string | null {
  let result = value.trim().replaceAll('µ', 'u').replaceAll('μ', 'u').replaceAll('Ω', '').replaceAll(' ', '')
  const unit = kind === 'source' ? 'v' : kind === 'capacitor' ? 'f' : kind === 'inductor' ? 'h' : ''
  if (unit && result.toLowerCase().endsWith(unit)) result = result.slice(0, -unit.length)
  if (!/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:meg|[tgkmunpf])?$/i.test(result)) return null
  return result
}

function spiceTime(value: string): string | null {
  let result = value.trim().replaceAll('µ', 'u').replaceAll('μ', 'u').replaceAll(' ', '')
  if (result.toLowerCase().endsWith('s')) result = result.slice(0, -1)
  return /^[+]?(?:\d+(?:\.\d*)?|\.\d+)(?:meg|[tgkmunpf])?$/i.test(result) ? result : null
}

function validReference(part: Part): boolean {
  const expected = ({ source: 'V', resistor: 'R', capacitor: 'C', ground: 'GND', inductor: 'L', diode: 'D', switch: 'S' } as const)[part.kind]
  return part.ref.startsWith(expected) && /^[A-Za-z][A-Za-z0-9_]*$/.test(part.ref)
}

export function createNetlist(project: Project): string {
  const connectivity = analyzeConnectivity(project)
  const rows = [`* ${cleanComment(project.name)}`, '* Generated by ELSim; edit the schematic to change this circuit.']
  let usesDiode = false

  for (const part of project.parts) {
    if (part.kind === 'ground') continue
    if (!validReference(part)) {
      rows.push(`* ERROR: ${cleanComment(part.ref)} has an invalid reference designator for ${part.kind}.`)
      continue
    }
    const positive = pinNet(connectivity, part, 0)
    const negative = pinNet(connectivity, part, 1)
    const value = spiceNumber(part.value, part.kind)
    if (part.kind !== 'diode' && part.kind !== 'switch' && value === null) {
      rows.push(`* ERROR: ${part.ref} has an invalid numeric value.`)
      continue
    }
    if (part.kind === 'source') rows.push(`${part.ref} ${positive} ${negative} PULSE(0 ${value} 0 1u 1u 50m 100m)`)
    else if (part.kind === 'resistor' || part.kind === 'capacitor' || part.kind === 'inductor') rows.push(`${part.ref} ${positive} ${negative} ${value}`)
    else if (part.kind === 'diode') { rows.push(`${part.ref} ${positive} ${negative} DDEFAULT`); usesDiode = true }
    else if (part.kind === 'switch') rows.push(`* ${part.ref} omitted: switch-control terminals are not implemented yet`)
  }

  if (usesDiode) rows.push('.model DDEFAULT D')
  const maxStep = spiceTime(project.simulation.maxStep)
  const stopTime = spiceTime(project.simulation.stopTime)
  if (maxStep && stopTime) rows.push(`.tran ${maxStep} ${stopTime}`)
  else rows.push('* ERROR: transient stop time and maximum step must be valid SPICE time values.')
  rows.push('.end')
  return rows.join('\n')
}

export function nextRef(parts: Part[], kind: Part['kind']): string {
  const prefix = ({ source: 'V', resistor: 'R', capacitor: 'C', ground: 'GND', inductor: 'L', diode: 'D', switch: 'S' } as const)[kind]
  const used = new Set(parts.map((part) => part.ref.toLowerCase()))
  let index = 1
  while (used.has(`${prefix}${index}`.toLowerCase())) index += 1
  return `${prefix}${index}`
}
